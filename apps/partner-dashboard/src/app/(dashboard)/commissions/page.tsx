'use client';

import type { CommissionDto } from '@wealthos/shared-types';
import {
  Badge,
  ErrorBanner,
  PageHeader,
  Spinner,
  StatCard,
  Table,
  Td,
  Th,
} from '@wealthos/ui-core';
import { formatDate, formatMoney, label } from '@/lib/format';
import { useApiData } from '@/lib/use-api-data';

interface Mrr {
  month: string;
  mrrPaise: number;
}

export default function CommissionsPage() {
  const { data, error, loading } = useApiData<CommissionDto[]>('/commissions');
  const { data: mrr, error: mrrError } = useApiData<Mrr>('/commissions/mrr');
  const upfront = data?.filter((item) => item.kind === 'UPFRONT').reduce((sum, item) => sum + item.amountPaise, 0) ?? 0;
  const trail = data?.filter((item) => item.kind === 'TRAIL').reduce((sum, item) => sum + item.amountPaise, 0) ?? 0;

  return (
    <div>
      <PageHeader
        title="Commission ledger"
        description="Upfront and trail earnings generated by your advised clients."
      />
      <ErrorBanner message={error ?? mrrError} />
      <div className="grid gap-4 sm:grid-cols-3">
        <StatCard label="Recorded upfront" value={formatMoney(upfront)} tone="positive" />
        <StatCard label="Recorded trail" value={formatMoney(trail)} tone="positive" />
        <StatCard
          label="Latest trail MRR"
          value={mrr ? formatMoney(mrr.mrrPaise) : '-'}
          hint={mrr ? `Period ${mrr.month}` : undefined}
        />
      </div>
      <div className="mt-6">
        {loading ? (
          <div className="flex items-center gap-3 text-sm text-slate-500">
            <Spinner /> Loading commission ledger...
          </div>
        ) : data && data.length > 0 ? (
          <Table>
            <thead>
              <tr>
                <Th>Created</Th>
                <Th>Kind</Th>
                <Th>Asset</Th>
                <Th>Rate</Th>
                <Th>Period</Th>
                <Th className="text-right">Amount</Th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100">
              {data.map((commission) => (
                <tr key={commission.id}>
                  <Td>{formatDate(commission.createdAt)}</Td>
                  <Td>
                    <Badge tone={commission.kind === 'UPFRONT' ? 'info' : 'success'}>
                      {label(commission.kind)}
                    </Badge>
                  </Td>
                  <Td>{label(commission.assetType)}</Td>
                  <Td className="tabular-nums">{(commission.rateBps / 100).toFixed(2)}%</Td>
                  <Td>{commission.periodMonth ?? '-'}</Td>
                  <Td className="text-right tabular-nums font-medium">{formatMoney(commission.amountPaise)}</Td>
                </tr>
              ))}
            </tbody>
          </Table>
        ) : (
          <p className="text-sm text-slate-500">No commissions recorded yet.</p>
        )}
      </div>
    </div>
  );
}
